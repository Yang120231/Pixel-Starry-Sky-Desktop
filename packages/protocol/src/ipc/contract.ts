/**
 * IPC 契约：桌面端所有 Electron IPC 通道的清单。纯数据，不导入 node / electron（远端辅助进程也会引用它）。
 * 目前只做声明，路由、参数解码、信任校验仍在各自模块里；`contract.test.ts` 和 `routing.test.ts` 负责保证两边一致。
 *
 * 字段：
 * - `kind`：`invoke`（渲染进程 `ipcRenderer.invoke`，主进程 `ipcMain.handle`）、`send`（`ipcRenderer.send`，主进程 `ipcMain.on`）、
 *   `sendSync`（同步 `sendSync`）、`push`（主进程 `webContents.send`，渲染进程 `ipcRenderer.on`）。
 * - `route`：多机器时这个通道去哪台机器。
 *   - `local`：只在本机执行，不经过 `Machines.invoke`；
 *   - `selected`：经过 `Machines.invoke`，跟随当前选中的机器（资源 ID 带机器前缀时跟着资源走）；
 *   - `resource`：经过 `Machines.invoke`，参数没有远端资源 ID 时留在本机；
 *   - `aggregate`：本机和所有远端的合并结果（`engine:projects`、`engine:sessions`）；
 *   - `hostOnly`：永远在本机，即使选中了远端机器；
 *   - `self`：处理函数自己按机器分流（`machines:*`、终端）；
 *   - `push`：主进程推给渲染进程的事件。
 * - `ids`：转发给远端时，哪些位置的字符串参数是资源 ID，需要去掉机器前缀（只管参数解码；路由只看第 0 个参数）。
 * - `picker`：需要本机的文件夹 / 文件选择对话框，选中了远端机器时报 `SSH_USE_WORKSPACE_PICKER`。
 * - `special`：`Machines.invoke` 对选中远端机器时的特殊处理（`files:copyPath`、`files:target`、`engine:usageExport`）。
 * - `remote`：远端辅助进程方法表里的方法名；只有确有远端实现的通道才写（可能与通道名不同）。
 * - `trust`：调用方校验的最低档位。`none` 不校验；`sender` 只验来源页面是应用自己的页面；
 *   `frame` 再验是顶层主框架；`window` 再验调用窗口存在（并与 webContents 一致）。
 */
export type IpcKind = 'invoke' | 'send' | 'sendSync' | 'push'
export type IpcRoute = 'local' | 'selected' | 'resource' | 'aggregate' | 'hostOnly' | 'self' | 'push'
export type IpcSpecial = 'copyPath' | 'target' | 'usageExport'
export type IpcTrust = 'none' | 'sender' | 'frame' | 'window'
export interface IpcChannelSpec {
  readonly kind: IpcKind
  readonly route: IpcRoute
  readonly ids?: readonly number[]
  readonly picker?: true
  readonly special?: IpcSpecial
  readonly remote?: string
  readonly trust: IpcTrust
}

